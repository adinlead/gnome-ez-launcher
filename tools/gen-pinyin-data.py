#!/usr/bin/env python3
"""
Generate src/pinyinData.js for the pinyin search feature.

Source data: mozillazg/pinyin-data (https://github.com/mozillazg/pinyin-data)
- Keeps only GB2312 common chars (~6763) to control the extension size
- Strips tone marks, keeps all readings of polyphonic chars
  (the default/most-common reading comes first)
- Emits a single ESM module exporting one string constant

Usage:
    python3 tools/gen-pinyin-data.py [path/to/pinyin.txt]

Without an argument the script downloads pinyin.txt from the fastly
jsDelivr CDN (raw.githubusercontent.com is unreachable from some networks).
"""

import os
import sys
import unicodedata
import urllib.request

SRC_URL = 'https://fastly.jsdelivr.net/gh/mozillazg/pinyin-data@master/pinyin.txt'
OUT_FILE = os.path.join(os.path.dirname(__file__), '..',
                        'src', 'strategies', 'zh-pinyin', 'data.js')


def gb2312_chars():
    """Build the set of GB2312 level-1+2 chars (covers ~all Chinese app names)."""
    chars = set()
    for b1 in range(0xB0, 0xF8):
        for b2 in range(0xA1, 0xFF):
            try:
                chars.add(bytes([b1, b2]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    return chars


def strip_tone(pinyin):
    """Strip tone marks: 'zhǎng' -> 'zhang'."""
    decomposed = unicodedata.normalize('NFD', pinyin)
    return unicodedata.normalize('NFC',
                                 ''.join(c for c in decomposed
                                         if not unicodedata.combining(c)))


def parse(source_file, allowed):
    """Parse pinyin.txt lines 'U+XXXX: py1,py2 # char' into {char: [readings]}."""
    table = {}
    with open(source_file, encoding='utf-8') as f:
        for line in f:
            if not line.startswith('U+'):
                continue
            code, rest = line.split(': ', 1)
            readings_field = rest.split('#', 1)[0]  # drop the trailing '# char' comment
            ch = chr(int(code[2:], 16))
            if ch not in allowed:
                continue
            # Dedupe stripped readings, preserve source order (default reading first)
            seen = set()
            pinyins = []
            for raw in readings_field.split(','):
                p = strip_tone(raw.strip())
                if p and p not in seen:
                    seen.add(p)
                    pinyins.append(p)
            if pinyins:
                table[ch] = pinyins
    return table


def main():
    if len(sys.argv) > 1:
        source = sys.argv[1]
    else:
        source = '/tmp/pinyin.txt'
        if not os.path.exists(source):
            print(f'Downloading {SRC_URL} ...')
            urllib.request.urlretrieve(SRC_URL, source)

    allowed = gb2312_chars()
    table = parse(source, allowed)

    # Entry format: one char per line, '长zhang,chang' (UTF-8, LF separated)
    data = '\n'.join(ch + ','.join(pys) for ch, pys in sorted(table.items()))

    # Pinyin letters and Han chars never contain '`' or '${', template literal is safe
    js = ('// Auto-generated by tools/gen-pinyin-data.py -- DO NOT EDIT.\n'
          '// Source: mozillazg/pinyin-data, filtered to GB2312 common chars, tones stripped.\n'
          '// Format: one entry per line "字reading1,reading2", default reading first.\n'
          'export default `' + data + '`;\n')

    with open(OUT_FILE, 'w', encoding='utf-8') as f:
        f.write(js)

    size_kb = os.path.getsize(OUT_FILE) / 1024
    print(f'Wrote {OUT_FILE}: {len(table)} chars, {size_kb:.1f} KB')


if __name__ == '__main__':
    main()
